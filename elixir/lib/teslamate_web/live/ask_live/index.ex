defmodule TeslaMateWeb.AskLive.Index do
  @moduledoc """
  "Ask" - a chat surface over the car's own data.

  The page is deliberately thin: `TeslaMate.Agent` owns the provider/tool loop
  and streams events back to this process (`{:agent_event, event}` ending with
  `:done`). The LiveView only keeps the rendered conversation, the composer and
  the run state, so a broken provider cannot leave the page half-working.

  Nothing the model writes is trusted: answers pass through
  `TeslaMateWeb.AgentMarkdown`, tool summaries are plain escaped text and chart
  SVGs are rendered raw only because they are generated by our own code.
  """

  use TeslaMateWeb, :live_view

  import TeslaMateWeb.Pengu, only: [pengu: 1]

  alias TeslaMate.Agent

  on_mount {TeslaMateWeb.InitAssigns, :locale}

  @max_question_length 1000

  # "Hey Pengu ..." / "Hey XPENG ..." is stripped, in the spirit of the car's own
  # wake word: the greeting is not part of the question.
  @wake_phrase ~r/\A\s*hey[\s,]+(?:pengu|xpeng)\b[:,]?\s*/i

  # How long the mascot stays awake after an answer (or an error) before it
  # settles back to idle. Configurable so tests do not sleep for six seconds.
  @pengu_awake_ms_default 6_000
  @max_replayed_turns 10
  @max_replayed_answer_length 4_000

  @impl true
  def mount(_params, %{"settings" => _settings}, socket) do
    socket =
      assign(socket,
        page_title: gettext("Ask"),
        enabled: false,
        configured: false,
        model: nil,
        daily_limit: 0,
        used: 0,
        blocked: true,
        turns: [],
        question: "",
        composer_error: nil,
        running: false,
        progress: nil,
        run_ref: nil,
        pengu: :idle,
        pengu_note: nil,
        pengu_sleep_ref: nil,
        pengu_art: TeslaMateWeb.Pengu.art?(),
        suggestions: suggestions()
      )

    {:ok, refresh_status(socket)}
  end

  defp suggestions do
    [
      gettext("Compare my consumption on my current tyres with my last set"),
      gettext("Which month had my best efficiency?"),
      gettext("How is my DC fast charging holding up?"),
      gettext("What does my battery health look like?")
    ]
  end

  # -- composer -------------------------------------------------------------

  @impl true
  def handle_event("update_question", params, socket) do
    question = to_string(params["content"] || "")
    socket = assign(socket, question: question, composer_error: nil)

    socket =
      cond do
        String.trim(question) == "" -> set_pengu(socket, :idle)
        socket.assigns.pengu == :idle -> set_pengu(socket, :listening)
        true -> socket
      end

    {:noreply, socket}
  end

  def handle_event("ask", params, socket) do
    submit_question(socket, params["content"])
  end

  def handle_event("suggestion", %{"question" => question}, socket) do
    submit_question(socket, question)
  end

  def handle_event("clear", _params, socket) do
    if socket.assigns.running do
      {:noreply,
       assign(socket,
         composer_error: gettext("Wait for the current answer before clearing the conversation.")
       )}
    else
      {:noreply,
       socket
       |> assign(
         turns: [],
         question: "",
         composer_error: nil,
         progress: nil
       )
       |> set_pengu(:idle)}
    end
  end

  # -- agent events ---------------------------------------------------------

  @impl true
  def handle_info({:agent_event, event}, socket) do
    {:noreply, handle_agent_event(socket, event)}
  end

  def handle_info({:pengu_sleep, ref}, socket) do
    if socket.assigns.pengu_sleep_ref == ref do
      {:noreply, set_pengu(socket, :idle)}
    else
      {:noreply, socket}
    end
  end

  def handle_info({:DOWN, ref, :process, _pid, _reason}, %{assigns: %{run_ref: ref}} = socket) do
    if socket.assigns.running do
      {:noreply,
       fail(socket, gettext("The assistant stopped before it could answer. Please try again."))}
    else
      {:noreply, assign(socket, run_ref: nil)}
    end
  end

  def handle_info({:DOWN, _ref, :process, _pid, _reason}, socket), do: {:noreply, socket}

  defp handle_agent_event(socket, {:progress, label}) when is_binary(label) do
    if socket.assigns.running do
      socket
      |> assign(progress: label)
      |> set_pengu(:thinking, label)
    else
      socket
    end
  end

  defp handle_agent_event(socket, {:tool, _name, summary}) when is_binary(summary) do
    socket
    |> update_last_turn(fn turn -> %{turn | tools: turn.tools ++ [summary]} end)
    |> set_pengu(:thinking, summary)
  end

  defp handle_agent_event(socket, {:chart, %{title: title, svg: svg}}) do
    if is_binary(svg) and String.starts_with?(String.trim_leading(svg), "<svg") do
      chart = %{title: to_string(title || ""), svg: svg}
      update_last_turn(socket, fn turn -> %{turn | charts: turn.charts ++ [chart]} end)
    else
      socket
    end
  end

  defp handle_agent_event(socket, {:answer, markdown}) when is_binary(markdown) do
    socket
    |> update_last_turn(fn turn -> %{turn | content: markdown} end)
    |> set_pengu(:speaking)
  end

  defp handle_agent_event(socket, {:meta, _meta}), do: socket

  defp handle_agent_event(socket, {:error, message}) do
    fail(socket, error_text(message))
  end

  defp handle_agent_event(socket, :done) do
    done(socket)
  end

  defp handle_agent_event(socket, _event), do: socket

  # -- submit ---------------------------------------------------------------

  defp submit_question(socket, raw) do
    {stripped, woke?} = strip_wake_phrase(raw)
    question = stripped |> to_string() |> String.trim()

    cond do
      socket.assigns.running ->
        {:noreply,
         assign(socket,
           composer_error: gettext("The assistant is still answering. Please wait a moment.")
         )}

      not socket.assigns.enabled ->
        {:noreply,
         assign(socket,
           composer_error: gettext("Ask is disabled. Enable it on the XpengMate page first.")
         )}

      not socket.assigns.configured ->
        {:noreply,
         assign(socket,
           composer_error:
             gettext("Add a DeepSeek API key on the XpengMate page before asking a question.")
         )}

      socket.assigns.used >= socket.assigns.daily_limit ->
        {:noreply,
         assign(socket,
           composer_error:
             gettext("You have used today's questions. Try again tomorrow or raise the limit.")
         )}

      question == "" and woke? ->
        {:noreply,
         socket
         |> set_pengu(:listening)
         |> assign(composer_error: gettext("I'm listening - ask me something about your car."))}

      question == "" ->
        {:noreply, assign(socket, composer_error: gettext("Type a question first."))}

      String.length(question) > @max_question_length ->
        {:noreply,
         assign(socket,
           composer_error:
             gettext("Questions are limited to %{limit} characters.",
               limit: @max_question_length
             )
         )}

      true ->
        start_question(socket, question)
    end
  end

  defp start_question(socket, question) do
    turn = %{role: :user, content: question, tools: [], charts: [], error: nil}

    socket =
      socket
      |> assign(
        turns: socket.assigns.turns ++ [turn, assistant_turn()],
        question: "",
        composer_error: nil,
        running: true,
        progress: gettext("Thinking…")
      )
      |> set_pengu(:thinking, gettext("Thinking…"))
      |> refresh_blocked()

    messages = replay_messages(socket.assigns.turns)

    case Agent.ask(messages, tz: TeslaMate.Setups.timezone(), notify: self()) do
      {:ok, pid} ->
        {:noreply, assign(socket, run_ref: Process.monitor(pid))}

      {:error, reason} ->
        {:noreply, fail(socket, error_text(reason))}
    end
  end

  # -- run state ------------------------------------------------------------

  defp done(socket) do
    socket
    |> assign(running: false, progress: nil, run_ref: nil)
    |> refresh_status()
    |> refresh_blocked()
    |> schedule_pengu_sleep()
  end

  defp fail(socket, message) do
    socket
    |> assign(running: false, progress: nil, run_ref: nil)
    |> update_last_turn(fn turn -> %{turn | error: message} end)
    |> set_pengu(:error)
    |> refresh_blocked()
    |> schedule_pengu_sleep()
  end

  # -- mascot ---------------------------------------------------------------

  # A new reference per mood makes a pending sleep message from an earlier mood
  # harmless: it no longer matches the current one.
  defp set_pengu(socket, state, note \\ nil) do
    assign(socket,
      pengu: state,
      pengu_note: note,
      pengu_sleep_ref: if(state == :idle, do: nil, else: make_ref())
    )
  end

  defp schedule_pengu_sleep(socket) do
    case socket.assigns.pengu_sleep_ref do
      ref when is_reference(ref) ->
        Process.send_after(self(), {:pengu_sleep, ref}, pengu_awake_ms())
        socket

      _ ->
        socket
    end
  end

  defp pengu_awake_ms do
    Application.get_env(:teslamate, :pengu_awake_ms, @pengu_awake_ms_default)
  end

  defp strip_wake_phrase(raw) do
    text = to_string(raw)

    case Regex.run(@wake_phrase, text) do
      [match | _] -> {String.replace_prefix(text, match, ""), true}
      nil -> {text, false}
    end
  end

  # -- conversation ---------------------------------------------------------

  defp assistant_turn do
    %{role: :assistant, content: nil, tools: [], charts: [], error: nil}
  end

  defp update_last_turn(socket, fun) do
    turns =
      case socket.assigns.turns do
        [] -> [fun.(assistant_turn())]
        turns -> List.update_at(turns, -1, fun)
      end

    assign(socket, turns: turns)
  end

  # Only the recent history is replayed on a follow-up: enough for the model to
  # keep the thread, bounded enough that the request cannot grow for ever.
  # Empty content is dropped first, so the not-yet-answered placeholder does
  # not consume one of the ten slots.
  defp replay_messages(turns) do
    messages =
      turns
      |> Enum.flat_map(fn turn ->
        case replay_content(turn) do
          "" -> []
          content -> [%{role: Atom.to_string(turn.role), content: content}]
        end
      end)
      |> Enum.take(-@max_replayed_turns)

    # The truncation may leave a dangling answer at the start of the transcript;
    # providers expect the history to open with the question it answered.
    case messages do
      [%{role: "assistant"} | rest] -> rest
      messages -> messages
    end
  end

  defp replay_content(%{role: :assistant, content: content}) when is_binary(content) do
    String.slice(content, 0, @max_replayed_answer_length)
  end

  defp replay_content(%{content: content}), do: to_string(content || "")

  # -- status ---------------------------------------------------------------

  defp refresh_status(socket) do
    status = Agent.status()

    socket
    |> assign(
      enabled: Map.get(status, :enabled, false),
      configured: Map.get(status, :configured, false),
      model: Map.get(status, :model),
      daily_limit: Map.get(status, :daily_limit, 0),
      used: Map.get(status, :used, 0)
    )
    |> refresh_blocked()
  end

  defp refresh_blocked(socket) do
    assigns = socket.assigns

    blocked =
      assigns.running or not assigns.enabled or not assigns.configured or
        assigns.used >= assigns.daily_limit

    assign(socket, blocked: blocked)
  end

  # -- errors ---------------------------------------------------------------

  defp error_text(:disabled) do
    gettext("Ask is disabled. Enable it on the XpengMate page first.")
  end

  defp error_text(:not_configured) do
    gettext("No API key is configured. Add one on the XpengMate page.")
  end

  defp error_text(:daily_limit) do
    gettext("You have used today's questions. Try again tomorrow or raise the limit.")
  end

  defp error_text(:conversation_too_long) do
    gettext("This conversation is too long. Clear it and start again.")
  end

  defp error_text(:busy), do: gettext("The assistant is still answering. Please wait a moment.")

  defp error_text(message) when is_binary(message) and message != "", do: message
  defp error_text(_message), do: gettext("The assistant could not answer. Please try again.")
end
